import { api, z, postgres } from "@superblocksteam/sdk-api";

const APPS_DB = "c6e32cf4-ca66-42ae-aeb3-58c84ffae574";

const T: Record<string, number> = {
  JT: 1, Tyler: 2, Brooke: 3, Carson: 4, AJ: 5,
  Adam: 6, Drew: 7, Erik: 8, Jimmy: 9, Chuck: 10, Jordan: 11,
};

interface TradeData {
  number: number;
  season: string;
  date: string;
  teamA: number;
  teamB: number;
  period: string;
  assetsFromA: Array<{ type: "player" | "pick"; name?: string; year?: number; round?: number; pickNum?: number }>;
  assetsFromB: Array<{ type: "player" | "pick"; name?: string; year?: number; round?: number; pickNum?: number }>;
}

function p(name: string): { type: "player"; name: string } {
  return { type: "player", name };
}

function pk(round: number, pickNum?: number, year?: number): { type: "pick"; year?: number; round: number; pickNum?: number } {
  return { type: "pick", round, pickNum, year };
}

export default api({
  name: "SeedHistoricalTradesV2",
  description: "Seeds historical trade data for seasons 2018-19 through 2022-23.",

  integrations: {
    apps_db: postgres(APPS_DB),
  },

  input: z.object({
    season: z.enum(["2018-19", "2019-20", "2020-21", "2021-22", "2022-23"]),
  }),

  output: z.object({
    message: z.string(),
    tradesInserted: z.number(),
  }),

  async run(ctx, { season }) {
    const tradeFns: Record<string, () => TradeData[]> = {
      "2018-19": get2018Trades,
      "2019-20": get2019Trades,
      "2020-21": get2020Trades,
      "2021-22": get2021Trades,
      "2022-23": get2022Trades,
    };

    const trades = tradeFns[season]();

    await ctx.integrations.apps_db.execute(
      `DELETE FROM ffwr_trades WHERE season = $1`,
      [season],
      { label: `Clear existing ${season} trades` }
    );

    let tradesInserted = 0;

    for (const trade of trades) {
      const tradeRows = await ctx.integrations.apps_db.query(
        `INSERT INTO ffwr_trades (trade_number, season, trade_date, team_a_id, team_b_id, status, period)
         VALUES ($1, $2, $3, $4, $5, 'accepted', $6)
         RETURNING id`,
        z.object({ id: z.coerce.number() }),
        [trade.number, trade.season, trade.date, trade.teamA, trade.teamB, trade.period],
        { label: `Insert trade #${trade.number}` }
      );

      const tradeId = tradeRows[0].id;

      for (const asset of trade.assetsFromA) {
        await ctx.integrations.apps_db.execute(
          `INSERT INTO ffwr_trade_assets (trade_id, from_team_id, asset_type, player_name, pick_year, pick_round, pick_number)
           VALUES ($1, $2, $3, $4, $5, $6, $7)`,
          [tradeId, trade.teamA, asset.type, asset.name ?? null, asset.year ?? null, asset.round ?? null, asset.pickNum ?? null],
          { label: `Asset A: ${asset.name ?? `R${asset.round}`}` }
        );
      }

      for (const asset of trade.assetsFromB) {
        await ctx.integrations.apps_db.execute(
          `INSERT INTO ffwr_trade_assets (trade_id, from_team_id, asset_type, player_name, pick_year, pick_round, pick_number)
           VALUES ($1, $2, $3, $4, $5, $6, $7)`,
          [tradeId, trade.teamB, asset.type, asset.name ?? null, asset.year ?? null, asset.round ?? null, asset.pickNum ?? null],
          { label: `Asset B: ${asset.name ?? `R${asset.round}`}` }
        );
      }

      tradesInserted++;
    }

    return { message: `Seeded ${tradesInserted} trades for ${season}`, tradesInserted };
  },
});

